-- ============================================================================
-- 演示租户（demo）组织架构对齐「教培机构」模型
--   背景：Snowy 初始种子把「小诺科技有限公司 + 10 个党政部门」落在了演示租户下，
--         导致首页问候语、组织架构页、班级/学员的「校区」下拉都出现与教培无关的名称。
--   处理：总部改名为租户名「示例机构」，保留一个校区「总校区」，
--         其余部门逻辑删除；业务数据的 CAMPUS_ID 统一指向校区。
--   幂等：可重复执行。
-- ============================================================================

-- 1) 总部 = 租户名称
UPDATE SYS_ORG SET NAME = '示例机构' WHERE ID = '1543842934270394368';

-- 2) 保留的校区
UPDATE SYS_ORG SET NAME = '总校区' WHERE ID = '1543842934270394370';

-- 3) 其余 Snowy 默认部门逻辑删除
UPDATE SYS_ORG SET DELETE_FLAG = 'DELETED'
WHERE ID IN ('1543842934270394371', '1543842934270394372', '1543842934270394373',
             '1543842934270394374', '1543842934270394375', '1543842934270394376',
             '1543842934270394377', '1543842934270394378');

-- 4) 业务数据的校区指向「总校区」
UPDATE STUDENT       SET CAMPUS_ID = '1543842934270394370' WHERE CAMPUS_ID = '1543842934270394368';
UPDATE STUDENT_ORDER SET CAMPUS_ID = '1543842934270394370' WHERE CAMPUS_ID = '1543842934270394368';
UPDATE COURSE_CLASS  SET CAMPUS_ID = '1543842934270394370' WHERE CAMPUS_ID = '1543842934270394368';
