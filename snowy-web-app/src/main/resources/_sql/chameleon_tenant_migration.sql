-- chameleon M1：底座表租户化迁移（一次性脚本，执行前请先备份）
-- 执行方式：mysql -uroot -p chameleon < chameleon_tenant_migration.sql
-- 依赖：先导入 snowy_mysql.sql + chameleon_platform.sql
-- 说明：
--   - MySQL 8.0 不支持 ADD COLUMN IF NOT EXISTS，本脚本只能执行一次；
--   - 现有数据全部归属演示租户（ID=1554740179362967450，即 chameleon_platform.sql 中的示例机构）；
--   - 平台级数据（后续 SaaS 运营用）使用 TENANT_ID='0'，由应用层写入。
-- ============================================================

